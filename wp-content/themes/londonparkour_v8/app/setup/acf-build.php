/**
 * `wp lp acf:build` — compose ACF definitions from PHP into acf-json/.
 *
 * Writes:
 *   - Field groups from block fields.php files and app/setup/acf-groups.php
 *   - lp_* post types and taxonomies from app/setup/cpt.php
 *
 * v7-imported field groups, post types, and taxonomies in acf-json/ are
 * preserved (see app/setup/acf-manifest.php). Use `--sync` to import all local
 * JSON into the database so items appear in the ACF admin UI.
 *
 * @package londonparkour_v8
 */

